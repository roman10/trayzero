// Run from mobile/: dart run tool/generate_launch_assets.dart
// Native launch assets only; does not modify launcher icons or task data.
import 'dart:convert';
import 'dart:io';
import 'dart:math' as math;
import 'package:image/image.dart' as img;

void main() {
  final source = File(
    'lib/core/appearance_preferences.dart',
  ).readAsStringSync();
  final amber = RegExp(
    r'const trayzeroSeedArgb = (0x[0-9A-F]+);',
  ).firstMatch(source)!.group(1)!;
  final colors = <String, String>{
    for (final match in RegExp(
      r"\w+\('([a-z]+)', (0x[0-9A-F]+|trayzeroSeedArgb)\)",
    ).allMatches(source))
      match.group(1)!:
          '#${(match.group(2) == 'trayzeroSeedArgb' ? amber : match.group(2)!).substring(4)}',
    'neutral': '@color/launch_artwork',
  };
  const res = 'android/app/src/main/res';
  for (final entry in colors.entries) {
    File('$res/drawable/splash_icon_${entry.key}.xml').writeAsStringSync(
      '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_launch_assets.dart. Safe-zone sunrise artwork. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="288dp" android:height="288dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="${entry.value}"
        android:pathData="M28,60 A26,26 0,0 1,80,60 Z M22,64 H86 V68 H22 Z" />
</vector>
''',
    );
  }
  File('$res/values/launch_icon_themes.xml').writeAsStringSync(
    '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_launch_assets.dart. -->
<resources>
${colors.keys.where((name) => name != 'neutral').map((name) => '''    <style name="LaunchTheme.${name[0].toUpperCase()}${name.substring(1)}" parent="LaunchTheme">
        <item name="windowSplashScreenAnimatedIcon">@drawable/splash_icon_$name</item>
    </style>''').join('\n')}
</resources>
''',
  );

  const asset = 'ios/Runner/Assets.xcassets/LaunchImage.imageset';
  final images = <Map<String, dynamic>>[];
  for (final dark in [false, true]) {
    for (var scale = 1; scale <= 3; scale++) {
      final name =
          'LaunchImage${dark ? '-dark' : ''}${scale == 1 ? '' : '@${scale}x'}.png';
      final size = 168 * scale;
      final raster = img.Image(
        width: size * 2,
        height: size * 2,
        numChannels: 4,
      );
      final gray = dark ? 189 : 102;
      for (var y = 0; y < raster.height; y++) {
        for (var x = 0; x < raster.width; x++) {
          final u = (x + 0.5) * 108 / raster.width;
          final v = (y + 0.5) * 108 / raster.height;
          final sun =
              v <= 60 && math.pow(u - 54, 2) + math.pow(v - 60, 2) <= 26 * 26;
          final horizon = u >= 22 && u <= 86 && v >= 64 && v <= 68;
          if (sun || horizon) raster.setPixelRgba(x, y, gray, gray, gray, 255);
        }
      }
      File('$asset/$name').writeAsBytesSync(
        img.encodePng(
          img.copyResize(
            raster,
            width: size,
            height: size,
            interpolation: img.Interpolation.average,
          ),
        ),
      );
      images.add({
        'idiom': 'universal',
        'filename': name,
        'scale': '${scale}x',
        if (dark)
          'appearances': [
            {'appearance': 'luminosity', 'value': 'dark'},
          ],
      });
    }
  }
  File('$asset/Contents.json').writeAsStringSync(
    '${const JsonEncoder.withIndent('  ').convert({
      'images': images,
      'info': {'version': 1, 'author': 'xcode'},
    })}\n',
  );
}
